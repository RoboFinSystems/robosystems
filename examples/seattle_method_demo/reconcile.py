def _read_graph_id_from_credentials() -> str | None:
  """Read the ``seattle_method_test`` graph slot from ``.local/config.json``.

  Returns ``None`` if the file or slot doesn't exist — caller surfaces
  a friendly "run the orchestrator first" message. The slot is saved
  by ``main.step_provision_graph`` via
  ``examples.credentials.utils.save_graph_id``.
  """
  import json

  config_path = Path(".local/config.json")
  if not config_path.exists():
    return None
  try:
    cfg = json.loads(config_path.read_text())
  except (OSError, json.JSONDecodeError):
    return None
  slot = (cfg.get("graphs") or {}).get("seattle_method_test") or {}
  return slot.get("graph_id")


def _get_ledger_client():
  """Construct a LedgerClient from saved credentials.

  Mirrors the helper used across the demo scripts. The GraphQL
  facade methods (``get_trial_balance``, ``list_information_blocks``)
  hang off this client.
  """
  import json

  from robosystems_client.clients.ledger_client import LedgerClient

  config_path = Path(".local/config.json")
  if not config_path.exists():
    raise SystemExit("Missing .local/config.json — run `just demo-user` first.")
  with config_path.open() as f:
    cfg = json.load(f)
  return LedgerClient(
    {
      "base_url": cfg.get("base_url", "http://localhost:8000"),
      "token": cfg["api_key"],
    }
  )


def _open_session(graph_id: str) -> Session:
  """Open a SQLAlchemy session scoped to the graph's schema.

  ``search_path`` is set so all subsequent queries against
  ``elements`` / ``line_items`` / ``entries`` / ``structures`` land
  in the right tenant schema. graph_id is validated against a strict
  regex before interpolation (SET search_path doesn't accept bind
  parameters).
  """
  if not SAFE_GRAPH_ID.match(graph_id):
    raise SystemExit(
      f"Refusing to use graph_id {graph_id!r} — must match {SAFE_GRAPH_ID.pattern}"
    )
  if not EXTENSIONS_DB_URL:
    raise SystemExit(
      "EXTENSIONS_DATABASE_URL is not set. Run via "
      "`just demo-seattle-method-reconcile <graph_id>` (which loads "
      ".env.local), or export the env var manually."
    )
  engine = create_engine(EXTENSIONS_DB_URL)
  session_factory = sessionmaker(bind=engine)
  session = session_factory()
  session.execute(text(f"SET search_path TO {graph_id}, public"))
  return session


def _load_concept_totals_via_graphql(
  client, graph_id: str, period_start: date, period_end: date
) -> list[ConceptTotal]:
  """Load per-concept period totals via the GraphQL trialBalance query.

  Replaces the prior direct-DB query against ``line_items``. The
  ``trialBalance`` resolver does the same aggregation server-side
  (Σ DR, Σ CR, net per account) — which means this script consumes
  the same query surface a frontend or MCP agent would.

  Returns ``ConceptTotal`` shapes scoped to ``mini:`` qnames only;
  rs-gaap and other taxonomies on the graph are filtered out
  client-side (the GraphQL query returns every CoA account).

  The trialBalance response shape per row:
  ``{account_id, account_code (=qname), account_name, trait,
  account_type, total_debits, total_credits, net_balance}``.
  Values come back as floats in dollars; we multiply by 100 for
  internal cents-precision.
  """
  data = client.get_trial_balance(
    graph_id,
    start_date=period_start.isoformat(),
    end_date=period_end.isoformat(),
  )
  rows = (data or {}).get("rows", []) or []

  totals: list[ConceptTotal] = []
  for r in rows:
    # ``account_code`` carries the mini qname (set at load time —
    # see ``load_taxonomy.build_element_payloads``).
    qname = r.get("account_code") or ""
    if not qname.startswith("mini:"):
      continue
    dollars_dr = float(r.get("total_debits") or 0)
    dollars_cr = float(r.get("total_credits") or 0)
    # Filter on "had activity" not "non-zero net" — Charlie's
    # Receivables has $8K DR + $8K CR netting to $0, but it's
    # legitimate activity that the diff should compare.
    if dollars_dr == 0 and dollars_cr == 0:
      continue
    debit_positive_cents = round((dollars_dr - dollars_cr) * 100)
    # trialBalance doesn't return period_type or balance_type
    # directly — they live on the Element row. Derive period_type
    # from trait (instant for asset/liability/equity, duration for
    # revenue/expense). For balance_type, infer from trait + sign.
    trait = r.get("trait")
    period_type = _period_type_from_trait(trait)
    balance_type = _balance_type_from_trait(trait)
    totals.append(
      ConceptTotal(
        qname=qname,
        label=r.get("account_name") or qname,
        balance_type=balance_type,
        period_type=period_type,
        trait=trait,
        debit_positive_cents=debit_positive_cents,
      )
    )

  # Synthesize mini:RetainedEarnings from cumulative (revenue - expense).
  # Mini has no source CoA element for RE — Charlie's renderer derives
  # it the same way our rs-gaap renderer does (see the
  # ``_close_to_retained_earnings`` family in fact_grid.py). We inject
  # it here so the reconciliation diff can compare against Charlie's
  # published ``mini:RetainedEarnings`` fact. For multi-period reports
  # this should also subtract cumulative dividends and add opening RE;
  # the Q1 2024 lemonade-stand starts at zero with no dividends so
  # RE_ending == NetIncome_current. This bidirectional projection
  # mirrors the rs-gaap path in
  # ``_append_empty_equity_facts``.
  ni_cents = sum(
    -c.debit_positive_cents
    for c in totals
    if c.trait in ("revenue", "expense") and c.period_type == "duration"
  )
  if ni_cents != 0:
    totals.append(
      ConceptTotal(
        qname="mini:RetainedEarnings",
        label="Retained Earnings",
        balance_type="credit",
        period_type="instant",
        trait="equity",
        # Credit-balance, debit-positive sign convention: a positive
        # net income (credit) stores as a negative debit-positive value.
        debit_positive_cents=-ni_cents,
      )
    )

  totals.sort(key=lambda c: c.qname)
  return totals


def _period_type_from_trait(trait: str | None) -> str:
  """Instant for BS concepts (asset/liability/equity), duration for IS."""
  if trait in ("asset", "liability", "equity", "contraAsset", "contraLiability"):
    return "instant"
  return "duration"


def _balance_type_from_trait(trait: str | None) -> str:
  """Debit for asset/expense/loss; credit for liability/equity/revenue/income/gain."""
  if trait in ("asset", "contraLiability", "contraEquity", "expense", "loss"):
    return "debit"
  return "credit"


def _load_expected_facts_from_instance(instance_path: Path) -> list[ExpectedFact]:
  """Parse Charlie's published XBRL ``instance.xml`` → list of ExpectedFact.

  The instance uses the XBRL 2003 schema (``http://www.xbrl.org/2003/instance``)
  for context and entity elements, with ``mini:`` (``http://www.xbrlsite.com/mini``)
  as the reporting taxonomy prefix.

  Two parse passes:

  1. Walk ``<context>`` elements → build ``{context_id: (period_kind, period_end)}``.
     Instant contexts use ``<instant>``; duration contexts use ``<startDate>`` /
     ``<endDate>``.
  2. Walk all child elements of the ``<xbrl>`` root that carry a ``contextRef``
     attribute and have numeric text content → emit one ExpectedFact each.

  Non-numeric facts (text blocks, units, schema refs) are filtered out.
  Values are stored as cents internally to match the rest of the
  reconciliation pipeline.
  """
  # instance.xml is a trusted artifact pulled by pull_expected_report.sh
  # from xbrlsite.com — not user-uploaded content — so the stdlib XML
  # parser is appropriate. If the input source ever widens, swap to
  # defusedxml.ElementTree.
  import xml.etree.ElementTree as ET

  ns_xbrli = "{http://www.xbrl.org/2003/instance}"
  tree = ET.parse(instance_path)
  root = tree.getroot()

  # Pass 1: contexts → {id: (kind, period_end_date)}
  contexts: dict[str, tuple[str, date]] = {}
  for ctx in root.findall(f"{ns_xbrli}context"):
    ctx_id = ctx.get("id")
    if not ctx_id:
      continue
    period = ctx.find(f"{ns_xbrli}period")
    if period is None:
      continue
    instant = period.find(f"{ns_xbrli}instant")
    end_date = period.find(f"{ns_xbrli}endDate")
    if instant is not None and instant.text:
      contexts[ctx_id] = ("instant", date.fromisoformat(instant.text.strip()))
    elif end_date is not None and end_date.text:
      contexts[ctx_id] = ("duration", date.fromisoformat(end_date.text.strip()))

  # Pass 2: facts. We iterate direct children of the xbrl root; numeric
  # facts carry ``contextRef`` + ``unitRef`` and have a numeric text
  # body. Schema/linkbase refs are XBRL-namespace elements (already
  # skipped by the contextRef check); contexts/units have no
  # contextRef.
  out: list[ExpectedFact] = []
  for elem in root:
    ctx_ref = elem.get("contextRef")
    if not ctx_ref or ctx_ref not in contexts:
      continue
    raw = (elem.text or "").strip()
    if not raw:
      continue
    try:
      dollars = float(raw)
    except ValueError:
      # Non-numeric facts (textBlock concepts, enumerations) — skip.
      continue

    # ElementTree gives us Clark-notation tags like
    # ``{http://www.xbrlsite.com/mini}CashAndCashEquivalents``; convert
    # to the canonical ``mini:CashAndCashEquivalents`` qname.
    tag = elem.tag
    if tag.startswith("{") and "}" in tag:
      ns_uri, local = tag[1:].split("}", 1)
      if ns_uri == "http://www.xbrlsite.com/mini":
        qname = f"mini:{local}"
      else:
        # Skip non-mini facts (gl:* entry concepts and similar). The
        # mini reconciliation scope is mini concepts only.
        continue
    else:
      continue

    kind, period_end = contexts[ctx_ref]
    out.append(
      ExpectedFact(
        concept=qname,
        period_kind=kind,
        period_end=period_end,
        value_cents=round(dollars * 100),
      )
    )
  return out


def _build_diff(
  ours: list[ConceptTotal],
  expected: list[ExpectedFact],
) -> list[ReconciliationLine]:
  """Diff our concept totals against Charlie's published instance.xml facts.

  Period matching is by ``period_kind`` (instant vs duration) rather
  than exact date — Charlie's instance reports BS positions at
  ``2024-12-31`` and IS/CF flows over ``2024-01-01..2024-12-31``,
  while our demo runs Q1 2024 (BS @ ``2024-03-31``, duration
  ``2024-01-01..2024-03-31``). The lemonade-stand fixture posts no
  activity outside Q1, so the ending positions and period flows
  match Charlie's calendar-year values by construction. If the
  fixture ever grows beyond Q1, this matcher needs to thicken
  (likely by aligning the demo's reporting period to Charlie's).

  Charlie also publishes the 2023-12-31 opening-balance facts (all
  zero) — we drop those from the diff since our renderer doesn't
  emit zero-line BS positions and they'd inflate the "missing fact"
  count without signal.

  Our debit-positive convention means we sign-flip credit-balance
  concepts (liabilities, equity, revenues) so the diff is meaningful
  against Charlie's presentation-positive values.
  """
  expected_by_concept_kind: dict[tuple[str, str], int] = {}
  for f in expected:
    # Skip prior-period zero rows — Charlie publishes them for context
    # but they aren't meaningful for our current-period reconciliation.
    if f.value_cents == 0 and f.period_end.year < 2024:
      continue
    expected_by_concept_kind.setdefault(
      (f.concept, f.period_kind), f.value_cents
    )

  diff_lines: list[ReconciliationLine] = []
  for c in ours:
    key = (c.qname, c.period_type)  # period_type matches "instant" / "duration"
    if key not in expected_by_concept_kind:
      continue

    # Sign convention: Charlie's published values are presentation-
    # positive (assets positive when grown, liabilities positive when
    # grown). Ours are debit-positive (credit-balance concepts come
    # in negative). Sign-flip credit-balance concepts.
    our_signed = (
      c.debit_positive_cents
      if c.balance_type == "debit"
      else -c.debit_positive_cents
    )
    diff_lines.append(
      ReconciliationLine(
        concept=c.qname,
        our_cents=our_signed,
        expected_cents=expected_by_concept_kind[key],
      )
    )
  return diff_lines


def _summarize_diff(lines: list[ReconciliationLine]) -> dict[str, int]:
  return {
    "lines_compared": len(lines),
    "exact_match": sum(1 for ln in lines if ln.status == "match"),
    "delta": sum(1 for ln in lines if ln.status == "delta"),
    "total_abs_delta_cents": sum(abs(ln.delta_cents) for ln in lines),
  }


def _derive_trait_from_concept(
  qname: str, balance_type: str | None, period_type: str | None
) -> str | None:
  """Mirror ``load_taxonomy._derive_trait`` — instant+debit → asset;
  instant+credit → liability (or equity by name match);
  duration+debit → expense; duration+credit → revenue."""
  if not balance_type or not period_type:
    return None
  if period_type == "instant":
    name_lower = qname.lower()
    equity_markers = (
      "paidincapital",
      "retainedearnings",
      "commonstock",
      "preferredstock",
      "treasurystock",
    )
    if any(m in name_lower for m in equity_markers):
      return "equity"
    return "asset" if balance_type == "debit" else "liability"
  return "revenue" if balance_type == "credit" else "expense"


def _load_rollforward_ibs_via_graphql(
  client, graph_id: str
) -> list[tuple[str, RollforwardMechanics]]:
  """Return [(structure_id, RollforwardMechanics), …] via GraphQL.

  Uses ``LedgerClient.list_information_blocks(block_type='rollforward')``
  — the same query the frontend / MCP / any external client would
  hit. The envelope's ``artifact.mechanics`` field carries the
  typed ``RollforwardMechanics`` JSON; we re-validate it through
  Pydantic to recover the typed shape (the hand-written GraphQL
  parser returns ``dict[str, Any]``).

  Note: the IB envelope's ``facts`` field is empty here (see
  ``information_block/rollforward.py:build_envelope``); the filter
  engine runs separately to produce the attributed facts.
  """
  blocks = client.list_information_blocks(graph_id, block_type="rollforward")
  out: list[tuple[str, RollforwardMechanics]] = []
  for block in blocks or []:
    artifact = block.get("artifact") or {}
    raw_mechanics = artifact.get("mechanics")
    if not raw_mechanics:
      continue
    mechanics = RollforwardMechanics.model_validate(raw_mechanics)
    out.append((block.get("id", ""), mechanics))
  return out


def _evaluate_all_rollforwards(
  session: Session,
  rollforwards: list[tuple[str, RollforwardMechanics]],
  period_start: date,
  period_end: date,
  bs_label_by_qname: dict[str, str],
) -> list[RollforwardResult]:
  """Run the filter engine for every rollforward IB; collect results."""
  results: list[RollforwardResult] = []
  for _structure_id, mech in rollforwards:
    facts = evaluate_attribution_filters(session, mech, period_start, period_end)
    # Compute the BS delta from the facts (matching + residual sum =
    # ΔBS by construction in residual_as_default mode).
    delta = sum(f.value_cents for f in facts)
    residual = sum(f.value_cents for f in facts if f.is_residual)
    results.append(
      RollforwardResult(
        bs_qname=mech.bs_source_qname,
        bs_label=bs_label_by_qname.get(mech.bs_source_qname, mech.bs_source_qname),
        delta_cents=delta,
        attributed=[f for f in facts if not f.is_residual],
        residual_cents=residual,
      )
    )
  return results


