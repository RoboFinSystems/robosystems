@dataclass
class ConceptTotal:
  """Sum of (debit - credit) on one concept across a period."""

  qname: str
  label: str
  balance_type: str  # 'debit' | 'credit'
  period_type: str  # 'instant' | 'duration'
  trait: str | None
  debit_positive_cents: int


@dataclass
class RollforwardResult:
  """One rollforward IB's filter engine output for a period."""

  bs_qname: str
  bs_label: str
  delta_cents: int  # ΔBS over the period (debit-positive)
  attributed: list[AttributedFact]
  residual_cents: int


@dataclass
class ExpectedFact:
  """One concept value from Charlie's published instance.xml.

  Sourced from ``local/datasets/seattle_method/report/instance.xml`` —
  the XBRL instance document Charlie publishes at
  ``xbrlsite.com/seattlemethod/platinum-testcases/record-to-report/``,
  generated by ``luca.auditchain.finance``. Parsed by
  :func:`_load_expected_facts_from_instance` rather than read from a
  hand-derived CSV — strictly stronger validation since it consumes the
  same artifact Arelle validates.
  """

  concept: str  # e.g. "mini:CashAndCashEquivalents"
  period_kind: str  # "instant" or "duration"
  period_end: date  # the instant date OR the duration end_date
  value_cents: int  # dollars from instance.xml x 100


@dataclass
class ReconciliationLine:
  """One line of the automated diff against Charlie's published facts."""

  concept: str
  our_cents: int
  expected_cents: int

  @property
  def delta_cents(self) -> int:
    return self.our_cents - self.expected_cents

  @property
  def status(self) -> str:
    if self.delta_cents == 0:
      return "match"
    return "delta"


